'use strict';
// Optional developer check: requires an existing Playwright and Chrome installation.
const {chromium} = require('playwright');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const {pathToFileURL} = require('node:url');
const assert = require('node:assert/strict');
(async()=>{
  const isolated = await fs.mkdtemp(path.join(os.tmpdir(),'ss3-standalone-'));
  const evidence = path.join(__dirname,'evidence');
  await fs.copyFile(path.join(__dirname,'../../SS-3.html'),path.join(isolated,'SS-3.html'));
  const browser = await chromium.launch({executablePath:process.env.CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
  try {
    const page = await browser.newPage({viewport:{width:1440,height:1080},acceptDownloads:true});
    const errors=[],network=[];
    page.on('pageerror',e=>errors.push(e.message));
    page.on('console',m=>{if(m.type()==='error') errors.push(m.text());});
    page.on('request',r=>{if(/^https?:/.test(r.url())) network.push(r.url());});
    page.on('dialog',d=>d.accept());
    await page.goto(pathToFileURL(path.join(isolated,'SS-3.html')).href);
    assert.equal(await page.locator('#concrete').textContent(),'0.869');
    assert.equal(await page.locator('#steel').textContent(),'76.000');
    await page.locator('#project-number').fill('SYNTHETIC SS-3 QA');
    await page.locator('#county').fill('Test county');
    await page.locator('#station').fill('100+00');
    await page.screenshot({path:path.join(evidence,'browser-desktop.png'),fullPage:true});
    await page.locator('#height').fill('2');
    assert.equal(await page.locator('#result-content').isVisible(),false);
    assert.equal(await page.locator('#print-report').isDisabled(),true);
    assert.equal(await page.locator('#save-project').isDisabled(),true);
    assert.equal(await page.locator('#schedule-total').textContent(),'');
    await page.locator('#use-minimum').click();
    await page.locator('#add-inlet').click();
    await page.locator('#inlet-type').selectOption('SS-4');
    assert.equal(await page.locator('#height').inputValue(),'3.125');
    assert.equal(await page.locator('#grate').textContent(),'—');
    await page.locator('#height').fill('4.5');
    assert.equal(await page.locator('#steel').textContent(),'31.000');
    const [download] = await Promise.all([page.waitForEvent('download'),page.locator('#save-project').click()]);
    const saved=JSON.parse(await fs.readFile(await download.path(),'utf8'));
    assert.equal(saved.inlets.length,2);
    assert.equal(saved.inlets[1].type,'SS-4');
    await page.locator('#inlet-id').fill('changed');
    await page.locator('#open-file').setInputFiles({name:'saved.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(saved))});
    await page.waitForFunction(()=>document.querySelector('#file-status').textContent.startsWith('Opened'));
    assert.equal(await page.locator('#inlet-select option').count(),2);
    assert.equal(await page.locator('#inlet-id').inputValue(),'1');
    await page.locator('#open-file').setInputFiles({name:'bad.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify({...saved,inlets:[{...saved.inlets[0],height:true}]}))});
    await page.waitForTimeout(150);
    assert.equal(await page.locator('#inlet-select option').count(),2);
    await page.setViewportSize({width:390,height:844});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    await page.screenshot({path:path.join(evidence,'browser-mobile.png')});
    await page.locator('#results-heading').scrollIntoViewIfNeeded();
    await page.screenshot({path:path.join(evidence,'browser-mobile-results.png')});
    // A longer project tests repeated table headers, page breaks and text escaping.
    saved.projectNumber='<script>window.injected=true</script>';
    saved.inlets=Array.from({length:12},(_,i)=>({...saved.inlets[i%2],id:String(i+1),station:`${100+i}+00`}));
    await page.locator('#open-file').setInputFiles({name:'report.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(saved))});
    await page.waitForFunction(()=>document.querySelectorAll('#report .report-inlet').length===12);
    assert.equal(await page.evaluate(()=>window.injected),undefined);
    await page.locator('#project-number').fill('SYNTHETIC SS-3 QA');
    await page.pdf({path:path.join(evidence,'report-sample.pdf'),format:'Letter',printBackground:true,preferCSSPageSize:true});
    const text=await page.locator('#report').textContent();
    assert.ok(text.includes('Inlet 12'));
    assert.ok(text.includes('31.000'));
    assert.deepEqual(network,[]);
    assert.deepEqual(errors,[]);
    console.log('PASS: isolated file:// load, live validation, SS-4, save/reopen, malformed import, escaping, mobile overflow, 12-inlet PDF, no network or browser errors.');
  } finally {await browser.close();await fs.rm(isolated,{recursive:true,force:true});}
})().catch(e=>{console.error(e);process.exitCode=1;});
