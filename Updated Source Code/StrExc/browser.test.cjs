'use strict';
// Developer check: use an existing playwright-core module and Chrome installation.
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright-core');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const {pathToFileURL} = require('node:url');
const assert = require('node:assert/strict');
(async () => {
  const isolated = await fs.mkdtemp(path.join(os.tmpdir(),'strexc-standalone-'));
  const evidence = path.join(__dirname,'evidence');
  await fs.copyFile(path.join(__dirname,'../../StrExc.html'),path.join(isolated,'StrExc.html'));
  const browser = await chromium.launch({executablePath:process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
  try {
    const context = await browser.newContext({viewport:{width:1440,height:1000},acceptDownloads:true,offline:true});
    const page = await context.newPage(), errors=[], network=[];
    page.on('pageerror',e=>errors.push(e.message));
    page.on('console',m=>{if(m.type()==='error') errors.push(m.text());});
    page.on('request',r=>{if(/^https?:/.test(r.url())) network.push(r.url());});
    let acceptDialog = true;
    page.on('dialog',d=>acceptDialog ? d.accept() : d.dismiss());
    await page.goto(pathToFileURL(path.join(isolated,'StrExc.html')).href);
    const field = (row,key) => page.locator(`#pipes tr:nth-child(${row}) [data-key=${key}]`);
    assert.equal(await page.locator('#export-excel').isDisabled(),true);
    const [draft] = await Promise.all([page.waitForEvent('download'),page.locator('#save-project').click()]);
    assert.equal(JSON.parse(await fs.readFile(await draft.path(),'utf8')).pipes[0].length,'');
    await page.locator('#project-name').fill('Synthetic excavation QA');
    await page.locator('#county').fill('Test county');
    await page.locator('#date').fill('2026-11-14');
    await field(1,'station').fill('001+00');
    await field(1,'length').fill('90'); await field(1,'depth').fill('3');
    assert.equal(await page.locator('#total-cy').textContent(),'35.00');
    await page.locator('#add-pipe').click();
    assert.equal(await page.locator('#total-cy').textContent(),'Pending');
    assert.equal(await page.locator('#export-excel').isDisabled(),true);
    await field(2,'station').fill('002+00'); await field(2,'size').selectOption('22x13');
    await field(2,'length').fill('54'); await field(2,'depth').fill('3'); await field(2,'fes').selectOption('2');
    assert.equal(await field(2,'size').locator('option:checked').textContent(),'22 x 13 arch');
    assert.equal(await page.locator('#total-cy').textContent(),'65.20');
    assert.equal(await page.locator('#pipes tr:nth-child(2) [data-output=type]').textContent(),'Arch');
    await field(2,'depth').fill('0');
    assert.equal(await page.locator('#export-excel').isDisabled(),true);
    assert.equal(await page.locator('#total-cy').textContent(),'Pending');
    await field(2,'depth').fill('3');
    const [xlsx] = await Promise.all([page.waitForEvent('download'),page.locator('#export-excel').click()]);
    await xlsx.saveAs(path.join(evidence,'sample-export.xlsx'));
    const [savedDownload] = await Promise.all([page.waitForEvent('download'),page.locator('#save-project').click()]);
    const saved = JSON.parse(await fs.readFile(await savedDownload.path(),'utf8'));
    await field(1,'length').fill('1');
    acceptDialog = false;
    await page.locator('#open-file').setInputFiles({name:'schedule.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(saved))});
    assert.equal(await field(1,'length').inputValue(),'1');
    acceptDialog = true;
    await page.locator('#open-file').setInputFiles({name:'schedule.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(saved))});
    await page.waitForFunction(()=>document.querySelector('#file-status').textContent.startsWith('Opened'));
    assert.equal(await page.locator('#total-cy').textContent(),'65.20');
    await page.locator('#open-file').setInputFiles({name:'bad.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify({...saved,pipes:[{...saved.pipes[0],length:true}]}))});
    await page.waitForFunction(()=>document.querySelector('#file-status').textContent.startsWith('Could not'));
    assert.equal(await page.locator('#pipes tr').count(),2);
    assert.equal(await page.locator('#total-cy').textContent(),'65.20');
    await field(1,'id').fill('<img src=x onerror=alert(1)>');
    assert.equal(await page.locator('#pipes img').count(),0);
    assert.equal(await page.locator('#pipes .remove').first().getAttribute('aria-label'),'Remove pipe <img src=x onerror=alert(1)>');
    await field(1,'id').fill('P-1');
    await page.locator('#save-project').click();
    await page.locator('h1').click();
    await page.screenshot({path:path.join(evidence,'browser-desktop.png'),fullPage:true});
    await context.grantPermissions([]);
    await page.emulateMedia({colorScheme:'dark'});
    await page.screenshot({path:path.join(evidence,'browser-dark.png'),fullPage:true});
    await page.emulateMedia({colorScheme:'light'});
    await page.setViewportSize({width:390,height:844});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    await page.screenshot({path:path.join(evidence,'browser-mobile.png'),fullPage:true});
    for (let i=0;i<2;i++) await page.locator('#pipes .remove').first().click();
    assert.equal(await page.locator('#empty-state').isVisible(),true);
    assert.equal(await page.locator('#export-excel').isDisabled(),true);
    await page.locator('#add-pipe').click();
    assert.equal(await page.locator('#pipes tr').count(),1);
    const many = {...saved,pipes:Array.from({length:500},(_,i)=>({...saved.pipes[i%2],id:`P-${i+1}`}))};
    await page.locator('#open-file').setInputFiles({name:'large.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(many))});
    await page.waitForFunction(()=>document.querySelectorAll('#pipes tr').length===500);
    assert.equal(await page.locator('#add-pipe').isDisabled(),true);
    assert.equal(await page.locator('#total-cy').textContent(),'16,300.00');
    const [large] = await Promise.all([page.waitForEvent('download'),page.locator('#export-excel').click()]);
    await large.saveAs(path.join(evidence,'large-export.xlsx'));
    assert.deepEqual(network,[]); assert.deepEqual(errors,[]);
    await fs.writeFile(path.join(evidence,'browser-results.json'),JSON.stringify({browser:await browser.version(),platform:process.platform,isolatedFile:true,offline:true,rows:500,errors,network},null,2)+'\n');
    console.log('PASS: isolated offline file, live calculations, validation, Excel downloads, draft save/reopen, cancelled replacement, bad import preservation, escaping, light/dark, mobile, empty state, 500 pipes; no network/errors.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode=1; });
